      void draw_mesh (const render::Mesh& mesh, const Mat4& model,
                      std::uint64_t motion_id) override {
        const auto& m = static_cast<const NhalMesh&> (mesh);
        if (!m.vertices)
          return;
        open_scene ();
        Mat4 previous = model;
        if (motion_id) {
          if (auto found = m_previous_models.find (motion_id);
              found != m_previous_models.end ())
            previous = found->second;
          m_current_models[motion_id] = model;
        }
        draw_runs ({}, m.vertices, m.runs, model, previous);
      }

      void reconstruct_scene () override {
        if (m_resolved)
          return;
        open_scene ();
        m_device->end_render_pass ();
        m_scene_open = false;
        Texture& previous = m_history[m_frame % 2];
        Texture& next = m_history[(m_frame + 1) % 2];
        RenderPassDesc pass;
        pass.label = "temporal resolve";
        pass.color_count = 1;
        pass.colors[0] = { next, Load::discard, Store::store };
        m_device->begin_render_pass (pass);
        m_device->set_pipeline (m_resolve);
        m_device->set_buffer (0, m_frame_block);
        m_device->set_texture (0, m_scene_color);
        m_device->set_texture (1, m_scene_motion);
        m_device->set_texture (2, m_scene_depth);
        m_device->set_texture (3, previous);
        m_device->draw (3);
        m_device->end_render_pass ();
        m_image = next;
        m_resolved = true;
      }

