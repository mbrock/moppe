    // The terrain's chunk levels, as the game's culling chooses them: a
    // step of source samples per rendered cell and vertices per chunk row.
    constexpr int chunk_cells = render::terrain_chunk_cells;
    constexpr int lod_count = int (render::TerrainLod::Count);
    constexpr float lod_step[lod_count] = { 0.25f, 1.0f, 2.0f, 4.0f, 8.0f };
    constexpr int lod_verts[lod_count] = { chunk_cells * 4 + 1, chunk_cells + 1,
                                           chunk_cells / 2 + 1,
                                           chunk_cells / 4 + 1,
                                           chunk_cells / 8 + 1 };

    // The trunk forest's (species, tier) classes, as forest_trunks.metal
    // numbers them: six detail tiers of birch, then six of spruce. A class's
    // topology -- facets, masses, and which vertices each triangle joins --
    // is a function of the two alone; world.lisp's forest-vertex places the
    // vertices in the same numbering.
    constexpr std::uint32_t forest_tiers = 6;
    constexpr std::uint32_t shadow_size = 2048;
    constexpr std::uint32_t forest_classes = 2 * forest_tiers;

    struct TreeTopology {
      std::uint32_t sides, crown_sides, masses;
      bool conifer, branches;

      TreeTopology (bool conifer_, std::uint32_t tier)
        : sides (tier >= 5 ? 10u : tier >= 2 ? 7u : 5u),
          crown_sides (sides == 10 ? 9u : sides),
          masses (conifer_ ? (tier >= 4 ? 5u : tier >= 1 ? 4u : 3u)
                           : (tier >= 4 ? 10u : tier >= 1 ? 7u : 4u)),
          conifer (conifer_), branches (!conifer_ && tier >= 3) {}

      std::uint32_t mass_vertices () const {
        return conifer ? crown_sides + 2 : 8 + (branches ? 6 : 0);
      }
      std::uint32_t mass_primitives () const {
        return conifer ? 2 * crown_sides : 12 + (branches ? 6 : 0);
      }

      void triangles (std::vector<std::uint16_t>& out) const {
        auto add = [&] (std::uint32_t a, std::uint32_t b, std::uint32_t c) {
          out.insert (out.end (), { std::uint16_t (a), std::uint16_t (b),
                                    std::uint16_t (c) });
        };
        // Three bands of quads between the trunk's four rings.
        for (std::uint32_t p = 0; p < sides * 6; ++p) {
          const std::uint32_t band = p / (2 * sides);
          const std::uint32_t quad = (p / 2) % sides;
          const std::uint32_t next = (quad + 1) % sides;
          const std::uint32_t a = band * sides + quad, b = band * sides + next;
          const std::uint32_t c = a + sides, d = b + sides;
          add ((p & 1) ? b : a, (p & 1) ? d : b, c);
        }
        for (std::uint32_t mass = 0; mass < masses; ++mass) {
          const std::uint32_t first = sides * 4 + mass * mass_vertices ();
          const std::uint32_t n = crown_sides;
          for (std::uint32_t p = 0; p < mass_primitives (); ++p) {
            if (conifer) {
              // A cone: its ring to the apex, then to the closing centre.
              const std::uint32_t side = p % n;
              add (first + side, first + (side + 1) % n,
                   first + (p < n ? n : n + 1));
            } else if (p < 12) {
              // A clump: six faces about its top tip, six about its bottom.
              const std::uint32_t k = p % 6;
              const std::uint32_t e0 = first + 2 + k;
              const std::uint32_t e1 = first + 2 + (k + 1) % 6;
              add (p < 6 ? first : first + 1, p < 6 ? e0 : e1,
                   p < 6 ? e1 : e0);
            } else {
              // Its branch, a three-sided prism.
              const std::uint32_t q = p - 12, k = q / 2;
              const std::uint32_t a = first + 8 + k;
              const std::uint32_t b = first + 8 + (k + 1) % 3;
              add ((q & 1) ? b : a, (q & 1) ? b + 3 : b, a + 3);
            }
          }
        }
      }
    };

    int patch_verts (int lod) {
      return (lod_verts[lod] - 1) * render::terrain_patch_cells / chunk_cells
             + 1;
    }

    std::array<float, 16> matrix (const Mat4& m) {
      std::array<float, 16> out;
      for (int i = 0; i < 16; ++i)
        out[i] = m.element (i);
      return out;
    }

    std::array<float, 4> lanes (const Vec3& v, float w = 0) {
      return { v[0], v[1], v[2], w };
    }

    std::array<float, 4> linear (DisplayColor c, float w = 0) {
      auto lin = [] (float x) { return std::pow (std::max (x, 0.0f), 2.2f); };
      return { lin (c.red), lin (c.green), lin (c.blue), w };
    }

    float halton (std::uint32_t index, std::uint32_t base) {
      float fraction = 1, result = 0;
      while (index > 0) {
        fraction /= float (base);
        result += fraction * float (index % base);
        index /= base;
      }
      return result;
    }

