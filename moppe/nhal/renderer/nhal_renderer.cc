      bool begin_frame (const FrameParams& params) override {
        if (!m_device->begin_frame ())
          return false;
        if (m_width != m_device->surface_width ()
            || m_height != m_device->surface_height ())
          make_targets ();
        m_params = params;
        m_scene_open = m_resolved = m_presented = false;

        const Mat4 view_proj = params.proj * params.view;
        if (m_restart)
          m_previous_view_proj = view_proj, m_previous_time = params.time;
        const float tan_x = 1.0f / params.proj.at (0, 0);
        const float tan_y = 1.0f / params.proj.at (1, 1);
        const std::uint32_t phase = m_frame++ % 16 + 1;

        FrameBlock frame {};
        frame.view_proj = matrix (view_proj);
        frame.previous_view_proj = matrix (m_previous_view_proj);
        frame.camera_position = lanes (params.camera_pos, params.time);
        frame.sun_direction = lanes (params.sun_dir, params.cloud_cover);
        frame.sun_diffuse = linear (params.sun_diffuse);
        frame.sun_specular = linear (params.sun_specular);
        frame.ambient = linear (params.ambient);
        frame.fog_color = linear (params.clear_color, params.fog_scale);
        frame.relief = { m_terrain_params.sea_level,
                         m_terrain_params.land_relief, m_previous_time, 0 };
        frame.view_right = lanes (params.cam_right * tan_x);
        frame.view_up = lanes (params.cam_up * tan_y);
        frame.view_forward = lanes (params.cam_forward);
        frame.temporal = { float (m_scene_width), float (m_scene_height),
                           (halton (phase, 2) - 0.5f) * 2
                             / float (m_scene_width),
                           (halton (phase, 3) - 0.5f) * 2
                             / float (m_scene_height) };
        frame.temporal_blend = { m_restart ? 1.0f : 0.1f, 0, float (m_width),
                                 float (m_height) };
        m_frame_block = m_device->allocate (sizeof frame);
        std::memcpy (m_frame_block.data, &frame, sizeof frame);

        m_previous_view_proj = view_proj;
        m_previous_time = params.time;
        m_restart = false;
        return true;
      }

      void draw_terrain (const ChunkDraw* chunks, int count) override {
        if (!m_have_terrain || count <= 0)
          return;
        open_scene ();
        m_device->set_pipeline (m_terrain);
        m_device->set_buffer (0, m_frame_block);
        shaders::terrain::Terrain terrain {};
        const auto& p = m_terrain_params;
        terrain.scale = { p.scale[0], p.scale[1], p.scale[2], p.tex_scale };
        terrain.fields = { m_landscape && m_ground ? 1.0f : 0.0f, 0, 0, 0 };
        terrain.size = { float (p.width), float (p.height), 0, 0 };
        m_device->set_uniforms (1, terrain);
        m_device->set_texture (0, m_heights);
        m_device->set_texture (1, m_normals);
        m_device->set_texture (2, texture_or_white (m_grass));
        m_device->set_texture (3, texture_or_white (m_dirt));
        m_device->set_texture (4, texture_or_white (m_rock));
        m_device->set_texture (5, texture_or_white (m_snow));
        m_device->set_texture (6, m_landscape ? m_landscape : m_white);
        m_device->set_texture (7, m_ground ? m_ground : m_white);
        for (int i = 0; i < count; ++i) {
          const ChunkDraw& c = chunks[i];
          const int lod = std::clamp (int (c.lod), 0, lod_count - 1);
          const bool patch = c.cells == render::terrain_patch_cells;
          shaders::terrain::Chunk chunk {};
          chunk.placement = { float (c.x0), float (c.z0), lod_step[lod],
                              float (patch ? patch_verts (lod)
                                           : lod_verts[lod]) };
          chunk.morph = { c.morph_start, c.morph_end,
                          lod_step[std::min (lod + 1, lod_count - 1)], 0 };
          chunk.offset = { c.offset_x, 0, c.offset_z, 0 };
          m_device->set_uniforms (2, chunk);
          m_device->draw_indexed (
            patch ? m_patch_indices[lod] : m_chunk_indices[lod],
            IndexType::uint32,
            patch ? m_patch_index_count[lod] : m_chunk_index_count[lod]);
        }
      }

