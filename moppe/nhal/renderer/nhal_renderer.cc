    std::uint32_t crc (const std::uint8_t* data, std::size_t size,
                       std::uint32_t c = 0xffffffffu) {
      static std::uint32_t table[256];
      if (!table[1])
        for (std::uint32_t n = 0; n < 256; ++n) {
          std::uint32_t v = n;
          for (int k = 0; k < 8; ++k)
            v = v & 1 ? 0xedb88320u ^ (v >> 1) : v >> 1;
          table[n] = v;
        }
      for (std::size_t i = 0; i < size; ++i)
        c = table[(c ^ data[i]) & 255] ^ (c >> 8);
      return c;
    }

    void write_png (const std::string& path, std::uint32_t width,
                    std::uint32_t height,
                    const std::vector<std::uint8_t>& rgb) {
      std::vector<std::uint8_t> raw;
      raw.reserve ((width * 3 + 1) * height);
      for (std::uint32_t y = 0; y < height; ++y) {
        raw.push_back (0);
        raw.insert (raw.end (), rgb.begin () + std::size_t (y) * width * 3,
                    rgb.begin () + std::size_t (y + 1) * width * 3);
      }
      // zlib with stored deflate blocks.
      std::vector<std::uint8_t> z { 0x78, 0x01 };
      std::uint32_t a = 1, b = 0;
      for (std::size_t at = 0; at < raw.size ();) {
        const std::size_t n = std::min<std::size_t> (65535, raw.size () - at);
        z.push_back (at + n == raw.size () ? 1 : 0);
        z.push_back (n & 255);
        z.push_back (n >> 8);
        z.push_back (~n & 255);
        z.push_back ((~n >> 8) & 255);
        z.insert (z.end (), raw.begin () + at, raw.begin () + at + n);
        for (std::size_t i = at; i < at + n; ++i) {
          a = (a + raw[i]) % 65521;
          b = (b + a) % 65521;
        }
        at += n;
      }
      const std::uint32_t adler = (b << 16) | a;
      for (int s = 24; s >= 0; s -= 8)
        z.push_back ((adler >> s) & 255);

      FILE* file = std::fopen (path.c_str (), "wb");
      if (!file)
        return;
      auto u32 = [] (std::vector<std::uint8_t>& v, std::uint32_t x) {
        for (int s = 24; s >= 0; s -= 8)
          v.push_back ((x >> s) & 255);
      };
      auto chunk = [&] (const char* type, const std::vector<std::uint8_t>& d) {
        std::vector<std::uint8_t> out;
        u32 (out, std::uint32_t (d.size ()));
        out.insert (out.end (), type, type + 4);
        out.insert (out.end (), d.begin (), d.end ());
        u32 (out, ~crc (out.data () + 4, out.size () - 4));
        std::fwrite (out.data (), 1, out.size (), file);
      };
      const std::uint8_t signature[8] = { 137, 80, 78, 71, 13, 10, 26, 10 };
      std::fwrite (signature, 1, 8, file);
      std::vector<std::uint8_t> header;
      u32 (header, width);
      u32 (header, height);
      header.insert (header.end (), { 8, 2, 0, 0, 0 });
      chunk ("IHDR", header);
      chunk ("IDAT", z);
      chunk ("IEND", {});
      std::fclose (file);
    }

    float half_to_float (std::uint16_t h) {
      const std::uint32_t e = (h >> 10) & 31, m = h & 1023;
      const float v = e == 0 ? std::ldexp (float (m), -24)
                      : e == 31 ? 65504.0f
                                : std::ldexp (float (m | 1024), int (e) - 25);
      return (h >> 15) ? -v : v;
    }

